const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const assert=require('node:assert/strict');
const base=process.env.ENGLISH_TEST_URL||'http://127.0.0.1:4175';
(async()=>{
  const browser=await chromium.launch();
  try{
    const page=await browser.newPage({viewport:{width:1440,height:1000}});
    const errors=[];page.on('pageerror',e=>errors.push(e.message));
    await page.goto(base+'/#library');await page.getByRole('heading',{name:'我的知识库',exact:true}).waitFor();
    await page.locator('#knowledge-search').fill('be resigned to doing something');
    await page.locator('.knowledge-row').click();await page.locator('#learning-answer').fill('接受不情愿但觉得无法改变的情况。');
    await page.locator('#study-minutes').fill('2');await page.locator('#mark-learned').click();
    await page.waitForFunction(()=>document.querySelector('.event-row')?.textContent.includes('首次学习'));
    const id=(new URL(page.url())).hash.split('/')[1];
    const first=await (await page.request.get(base+'/api/learning/item?id='+id)).json();
    assert.equal(first.progress.length,1);assert.equal(first.events[0].minutes,2);
    await page.reload();await page.locator('.event-row').waitFor();assert.equal(await page.locator('#mark-learned').isDisabled(),true);
    await page.locator('#practice-now').click();await page.locator('#reveal-answer').waitFor();
    assert.equal(await page.locator('#review-answer').isVisible(),false);
    await page.locator('#learning-answer').fill('想不起来了');await page.locator('#assistance').selectOption('hint');
    await page.locator('#reveal-answer').click();await page.locator('[data-rating="forgot"]').click();
    await page.getByRole('heading',{name:'今日复习',exact:true}).waitFor();
    await page.goto(base+'/#learn/'+id);await page.locator('[data-undo]').first().click();
    await page.waitForFunction(()=>document.querySelector('.event-row')?.textContent.includes('已撤销'));
    const undone=await (await page.request.get(base+'/api/learning/item?id='+id)).json();assert.equal(undone.progress[0].due,first.progress[0].due);
    await page.locator('#learning-mode').selectOption('express');await page.locator('#mark-learned').click();
    await page.waitForFunction(()=>[...document.querySelectorAll('.event-row')].some(e=>e.textContent.includes('表达 · 首次学习')));
    const two=await (await page.request.get(base+'/api/learning/item?id='+id)).json();assert.equal(two.progress.length,2);
    await page.goto(base+'/#import');await page.locator('#import-text').fill('workbench test word\t测试义一\nworkbench test word\t测试义二');
    await page.locator('#import-kind').selectOption('word');await page.locator('#preview-import').click();
    await page.locator('.import-candidate').first().waitFor();assert.equal(await page.locator('.import-candidate').count(),2);
    await page.locator('#confirm-import').click();await page.getByRole('heading',{name:'我的知识库',exact:true}).waitFor();
    await page.locator('#knowledge-search').fill('workbench test word');await page.waitForFunction(()=>document.querySelector('#knowledge-count')?.textContent.includes('找到 2 项'));assert.equal(await page.locator('.knowledge-row').count(),2);
    await page.goto(base+'/#import');await page.locator('#import-text').fill('workbench test word\t测试义一');await page.locator('#import-kind').selectOption('word');await page.locator('#preview-import').click();await page.locator('.import-candidate').waitFor();assert.equal(await page.locator('.import-candidate input[type=checkbox]').isChecked(),false);
    await page.goto(base+'/#'+encodeURIComponent('book/03-四六级词汇/01-familiar-verbs.md'));await page.locator('.entry-link').first().waitFor();
    await page.locator('.entry-link').first().click();await page.locator('#mark-learned').waitFor();
    await page.screenshot({path:'/tmp/english-workbench-detail.png'});
    await page.goto(base+'/#library');await page.getByRole('heading',{name:'我的知识库',exact:true}).waitFor();
    await page.screenshot({path:'/tmp/english-workbench-library.png'});
    assert.deepEqual(errors,[]);
    console.log('PASS: learn, reload, independent modes, review, undo, batch import, distinct senses, duplicates, book links.');
  }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
